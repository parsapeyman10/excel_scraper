RTL_LANGUAGES = {"fa", "ar", "he", "ur"}


class Translator:
    def __init__(self, language: str = "fa"):
        self.language = language if language in STRINGS else "en"

    def __call__(self, key: str, default: str | None = None) -> str:
        table = STRINGS.get(self.language, STRINGS["en"])
        return table.get(key, STRINGS["en"].get(key, default if default is not None else key))

    @property
    def is_rtl(self) -> bool:
        return self.language in RTL_LANGUAGES

    def set_language(self, language: str) -> None:
        self.language = language if language in STRINGS else "en"
